#!/usr/bin/env bash
# Integration test: the rig satisfies docs/server-setup.md's prerequisites table.
#
# The rig is treated as given: this suite never starts, resets or stops it. A
# test that repairs its own environment hides that cost and turns "the rig is
# broken" into "some test failed somewhere", so an unreachable rig is a loud
# precondition failure here, not a skip and not a `rig.sh up`.
#
# Exit status follows test.sh's contract: 0 pass, 1 an assertion about the rig
# failed, 2 the suite could not run at all. A downed rig is the operator's
# environment, not a fact about the code under test, and reporting it as 1 sends
# the reader hunting for a defect that is not there.

set -uo pipefail

repo_dir="$(cd "$(dirname "$0")/../.." && pwd)"
# The single copy of the connection contract — port, key, host-key policy,
# BatchMode, ConnectTimeout — regenerated by every rig.sh invocation. Restating
# any of those flags here would create a second contract that drifts from it.
ssh_config="$repo_dir/tests/rig/ssh_config"
ssh_alias=rig

fail=0
assert() {
    if ! eval "$1"; then
        echo "  FAIL: $2" >&2
        fail=1
    fi
}

tmpdir="$(mktemp -d)"
trap 'rm -rf "$tmpdir"' EXIT

if [ ! -f "$ssh_config" ]; then
    echo "error: no $ssh_config" >&2
    echo "       the integration suite needs a running rig: tests/rig/rig.sh up" >&2
    exit 2
fi

# A single SSH session collects every fact, for two reasons. The rig's sshd runs
# `maxstartups 10:30:100`, so a session per assertion is a flake generator once
# suites grow; and a session costs ~0.2 s, which a batch amortises to nothing.
# The remote script reports facts and always exits 0 — the verdicts are local,
# so a non-zero status here can only mean the transport or the timeout fired.
#
# ssh_config's ConnectTimeout bounds only the connection *setup*: an established
# session that then stalls — a wedged rig, or a pull that gets TCP and no bytes —
# would hang forever, and this suite must never hang. 120 s against an observed
# ~4 s run is far outside the noise but still bounded.
probe_timeout=120
probe_err="$tmpdir/probe.err"
probe_out=$(timeout "$probe_timeout" ssh -F "$ssh_config" "$ssh_alias" bash -s 2>"$probe_err" <<'REMOTE'
set -uo pipefail

kv() { printf '%s=%s\n' "$1" "$2"; }

kv user "$(id -un)"

# `docker version` rather than `docker info`: the prerequisites table's ">= 24"
# is about the daemon, and asking the daemon its version also proves this user
# reaches it at all — which is the "can run docker without sudo" row, since
# this script runs unelevated as the SSH user.
kv docker_server "$(docker version --format '{{.Server.Version}}' 2>/dev/null)"
kv compose_version "$(docker compose version --short 2>/dev/null)"

for c in rsync openssl gzip; do
    if command -v "$c" >/dev/null 2>&1; then kv "have_$c" yes; else kv "have_$c" no; fi
done

# A CLI that answers is not a working daemon: pulling and running an image
# exercises the network, the storage driver and containerd inside the rig.
hello_out=$(docker run --rm hello-world 2>&1); hello_rc=$?
kv hello_rc "$hello_rc"
kv hello_greeting "$(grep -c 'Hello from Docker!' <<<"$hello_out")"
[ "$hello_rc" -eq 0 ] || kv hello_output "$(tr '\n' ' ' <<<"$hello_out")"

# Drop the image this test just pulled. The rig outlives the run, and a cached
# hello-world would leave the next run asserting only that a local image starts
# — the pull is half of what "docker functional" means here.
docker rmi -f hello-world >/dev/null 2>&1

exit 0
REMOTE
); probe_rc=$?

# 124 is timeout(1)'s own "expired" status; reporting it as a transport failure
# would send the next reader to look at ssh instead of at the wedged rig.
if [ "$probe_rc" -eq 124 ]; then
    echo "error: the rig probe did not finish within ${probe_timeout}s" >&2
    sed 's/^/       ssh: /' "$probe_err" >&2
    echo "       the rig is wedged, or the hello-world pull stalled mid-transfer" >&2
    exit 2
fi

if [ "$probe_rc" -ne 0 ] || [ -z "$probe_out" ]; then
    echo "error: could not run the probe on the rig (ssh exit $probe_rc)" >&2
    sed 's/^/       ssh: /' "$probe_err" >&2
    echo "       is the rig up? tests/rig/rig.sh up" >&2
    exit 2
fi

# The probe output is a protocol, so it is validated as one: parsed once, then
# checked for completeness *before* any assertion reads it. The alternative —
# looking keys up lazily — lets a key that never arrived be absorbed into a
# downstream comparison, and a missing fact must never be able to produce a
# passing assertion. `hello_output` is deliberately absent from the required
# set: the probe only emits it when hello-world failed.
declare -A fact=()
while IFS= read -r line; do
    case $line in *=*) fact[${line%%=*}]=${line#*=} ;; esac
done <<<"$probe_out"

missing=()
for key in user docker_server compose_version have_rsync have_openssl have_gzip \
           hello_rc hello_greeting; do
    [ -n "${fact[$key]+set}" ] || missing+=("$key")
done
if [ "${#missing[@]}" -gt 0 ]; then
    echo "error: the rig probe reported no ${missing[*]}" >&2
    echo "       the probe script broke, or its output was truncated — raw output:" >&2
    sed 's/^/       | /' <<<"$probe_out" >&2
    exit 2
fi

major() { printf '%s' "${1%%.*}"; }

# --- Row: SSH with key auth to user@host --------------------------------------
# Already proven by the probe running at all: ssh_config pins `BatchMode yes`
# and `IdentitiesOnly yes` with an explicit IdentityFile, so no password or
# agent key could have been used. What is left to check is who we became.
remote_user="${fact[user]}"
assert '[ "$remote_user" = "stevedore" ]' \
    "ssh lands as stevedore (got '$remote_user')"
assert '[ "$remote_user" != "root" ]' \
    "the SSH user is unprivileged — as root the no-sudo row below is vacuous (got '$remote_user')"

# --- Row: Docker >= 24 --------------------------------------------------------
docker_server="${fact[docker_server]}"
docker_major="$(major "$docker_server")"
assert '[ -n "$docker_server" ]' \
    "the docker daemon reports a version (docker version --format {{.Server.Version}} produced nothing)"
assert '[[ "$docker_major" =~ ^[0-9]+$ ]] && [ "$docker_major" -ge 24 ]' \
    "docker >= 24 required by docs/server-setup.md (rig reports '$docker_server')"

# --- Row: Docker Compose v2 ---------------------------------------------------
compose_version="${fact[compose_version]}"
compose_major="$(major "$compose_version")"
assert '[ -n "$compose_version" ]' \
    "docker compose is available as a plugin (docker compose version --short produced nothing)"
assert '[[ "$compose_major" =~ ^[0-9]+$ ]] && [ "$compose_major" -ge 2 ]' \
    "docker compose v2 or newer (rig reports '$compose_version')"

# --- Row: the SSH user can run docker without sudo ----------------------------
# The probe never elevated, so a version from the daemon *is* the proof; this
# assertion exists to name the row when it is the thing that broke.
assert '[ -n "$docker_server" ]' \
    "$remote_user reaches the docker daemon without sudo (no daemon version came back)"

# --- The suites' own tools on the remote: rsync (the sync parity reference),
# openssl, gzip --------------------------------------------------------------
for cmd in rsync openssl gzip; do
    have="${fact[have_$cmd]}"
    assert '[ "$have" = "yes" ]' "$cmd is present on the remote (command -v reported '$have')"
done

# --- Exit criterion: docker is functional inside the rig ----------------------
hello_rc="${fact[hello_rc]}"
hello_greeting="${fact[hello_greeting]}"
# The container's output is only reported when it failed, so the detail is
# appended conditionally — inlined, it would leave a dangling separator and an
# empty value on the passing path.
hello_detail=""
[ "$hello_rc" = "0" ] || hello_detail=" — ${fact[hello_output]-}"
assert '[ "$hello_rc" = "0" ]' \
    "docker run --rm hello-world succeeds in the rig (exit $hello_rc$hello_detail)"
assert '[ "$hello_greeting" != "0" ]' \
    "hello-world printed its greeting (matched 'Hello from Docker!' $hello_greeting times)"

exit "$fail"
